    private void btnEditar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditar1ActionPerformed
     String idConsultaStr = txtConsulta.getText().trim();
    if (idConsultaStr.isEmpty() || lblId1.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Primero busca un accesorio válido para editarlo.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }
 
    try {
        int idOriginal = Integer.parseInt(idConsultaStr);
        
        // Recoger y convertir los valores de los campos
        int idAccesorio = Integer.parseInt(lblId1.getText().trim());
        String nombre = txtNombre.getText().trim();
        String strTipo = (String) ComboBoxTipo.getSelectedItem();
        double precio = Double.parseDouble(txtPrecio.getText().trim());
        String marca = txtNumeroLlaves.getText().trim();
        int idInstrumento = Integer.parseInt(txtTipoBoquilla.getText().trim());
 
        AccesorioCuerda.tipo tipoAccesorio;
        try {
            tipoAccesorio = AccesorioCuerda.tipo.valueOf(strTipo.toUpperCase());
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "El tipo debe ser CUERDAPULSADA o CUERDAFROTADA.", "Tipo inválido", JOptionPane.ERROR_MESSAGE);
            return;
        }
 
        // Crear instancia con los nuevos datos del accesorio de cuerda
        AccesorioCuerda accesorioActualizado = new AccesorioCuerda(idAccesorio, nombre, tipoAccesorio, precio, marca, idInstrumento);
     
        // Actualizar usando el servicio
        servicioInstrumentos.actualizarAccesorio(idOriginal, accesorioActualizado);
        
        JOptionPane.showMessageDialog(this, "Accesorio actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Revisa que ID, Precio e ID de Instrumento sean numéricos.", "Error de formato", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        // Captura las excepciones de validación, como un ID de instrumento inexistente
        JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnEditar1ActionPerformed

