    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
              String idStr = txtConsulta.getText().trim();
 
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, ingresa el ID del instrumento a buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }
 
    try {
        int idConsulta = Integer.parseInt(idStr);
 
        AccesorioCuerda accesorio = servicioInstrumentos.buscarAccesorioCuerda(idConsulta);
 
        if (accesorio != null) {
            // Llenar los campos con los valores del accesorio de cuerda
            lblId1.setText(String.valueOf(accesorio.getId()));
            txtNombre.setText(accesorio.getNombre());
            ComboBoxTipo.setSelectedItem(accesorio.getTipo().toString());
            txtPrecio.setText(String.valueOf(accesorio.getPrecio()));
            txtNumeroLlaves.setText(accesorio.getMarca());
            txtTipoBoquilla.setText(String.valueOf(accesorio.getIdInstrumento()));
            
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró ningún accesorio de cuerda con ese ID.", "No Encontrado", JOptionPane.ERROR_MESSAGE);
            // Limpiar los campos 
            lblId1.setText(""); txtNombre.setText(""); ComboBoxTipo.setSelectedIndex(0);
            txtPrecio.setText(""); txtNumeroLlaves.setText(""); txtTipoBoquilla.setText("");
        }
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID debe ser un número entero válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Ocurrió un error al buscar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

